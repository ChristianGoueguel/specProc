test_that("renamed arguments still work, with a deprecation warning", {
  rlang::local_options(lifecycle_verbosity = "warning")
  x <- c(1, 2, NA, 4, 10)
  expect_warning(z <- zscore(x, drop.na = TRUE), "drop_na")
  expect_equal(z, zscore(x, drop_na = TRUE))
  m <- matrix(stats::rnorm(40, 10), 4)
  expect_warning(s <- snv(m, drop.na = FALSE), "drop_na")
  expect_equal(s, snv(m, drop_na = FALSE))
  expect_warning(b <- baseline_als(m, max.iter = 5), "max_iter")
  expect_equal(b, baseline_als(m, max_iter = 5))
  expect_no_warning(baseline_als(m, max_iter = 5))
  p <- c(0.1, 0.5, 0.9)
  expect_warning(q <- tukey_gh(log(p), "q", g = 0.2, h = 0.1, log.p = TRUE), "log_p")
  expect_equal(q, tukey_gh(log(p), "q", g = 0.2, h = 0.1, log_p = TRUE))
  expect_equal(q, tukey_gh(p, "q", g = 0.2, h = 0.1))
  expect_warning(d <- directional_outlyingness(x, cutoff.quantile = 0.9), "cutoff_quantile")
  expect_equal(d, directional_outlyingness(x, cutoff_quantile = 0.9))
  y <- c(0, 0, 0, 1, 5, 3, 9, 2, 6, 4, 8, 7, 1e3)
  expect_warning(d <- directional_outlyingness(y, rmZeroes = TRUE), "rm_zeroes")
  expect_equal(d, directional_outlyingness(y, rm_zeroes = TRUE))
  expect_warning(d <- directional_outlyingness(y, maxRatio = 3), "max_ratio")
  expect_equal(d, directional_outlyingness(y, max_ratio = 3))
  expect_warning(d <- directional_outlyingness(y, precScale = 1e-8), "prec_scale")
  expect_equal(d, directional_outlyingness(y, prec_scale = 1e-8))
})

test_that("average() takes the deprecated .group_by unquoted or as a string", {
  rlang::local_options(lifecycle_verbosity = "warning")
  df <- data.frame(id = c("a", "a", "b"), v = c(1, 3, 5))
  expected <- average(df, id)
  expect_equal(average(df, group_by = "id"), expected)
  expect_warning(a <- average(df, .group_by = id), "group_by")
  expect_equal(a, expected)
  expect_warning(a <- average(df, .group_by = "id"), "group_by")
  expect_equal(a, expected)
  expect_no_warning(average(df["v"]))
})

